import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {tmpdir} from 'node:os';
import assert from 'node:assert/strict';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const output=resolve(tmpdir(),'FactoryLean-Maintenance-Stops-20261012','browser');await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'msedge'}),context=await browser.newContext({viewport:{width:1280,height:1000}});
await context.route('**/*',route=>route.request().url().startsWith('http://127.0.0.1:4205/')?route.continue():route.abort());
const page=await context.newPage(),errors=[],report=[];page.on('pageerror',e=>errors.push(e.message));
try {
 await page.goto('http://127.0.0.1:4205/?view=stops');
 const choice=page.getByLabel('Scheduled maintenance (optional)');await choice.locator('option').nth(1).waitFor({state:'attached'});
 assert.equal(await choice.inputValue(),'');report.push('PASS no implicit maintenance selection; ordinary stop remains default');
 await choice.selectOption({index:1});assert.match(await page.locator('output').innerText(),/MR-QA-1/);report.push('PASS explicit schedule selection, title/window and revalidation notice');
 await page.getByRole('heading',{name:'Actual maintenance stops'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Remove association',exact:true}).count(),1);report.push('PASS two actual stops; only closed stop offers correction');
 await page.getByText('Stop association history',{exact:true}).click();
 assert.match(await page.locator('.mr-linked-stop').innerText(),/previously saved Loss review/);report.push('PASS immutable history and saved-evidence notice');
 await page.getByRole('button',{name:'Remove association',exact:true}).click();
 const form=page.locator('.mr-linked-stop form');assert.ok(await form.getByRole('button',{name:'Remove association'}).isDisabled());
 await form.getByLabel('Reason for correction',{exact:true}).fill('Synthetic closed association correction');
 await form.getByRole('button',{name:'Remove association'}).click();await page.locator('.mr-linked-stop [role="alert"]').waitFor();
 const first=await page.evaluate(()=>window.commands[0]);assert.equal(first.name,'correct_maintenance_stop');assert.equal(first.args.operation,'UNLINK');assert.equal(first.args.expected_revision,1);
 await form.getByRole('button',{name:'Remove association'}).click();await page.waitForFunction(()=>window.commands.length===2);
 const commands=await page.evaluate(()=>window.commands);assert.equal(commands[0].args.request_id,commands[1].args.request_id);
 report.push('PASS mandatory reason and unchanged retry identity; synthetic writer rejects, displayed stock/stop state unchanged');
 await page.screenshot({path:join(output,'stops-desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'Edit authority: on',exact:true}).click();
 assert.equal(await page.locator('.mr-linked-stop').getByRole('button',{name:'Remove association',exact:true}).count(),0);
 report.push('PASS correction controls hidden without edit authority');
 await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:4205/?view=stops&lang=ar');
 await page.getByRole('heading',{name:'توقفات الصيانة الفعلية'}).waitFor();
 await page.getByText('توقف صيانة مجدولة',{exact:false}).first().waitFor();
 assert.equal(await page.locator('html').getAttribute('dir'),'rtl');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:join(output,'stops-ar-mobile.png'),fullPage:true});report.push('PASS Arabic/RTL 390px without horizontal page overflow');
 await page.route('**/api/maintenance?*',route=>route.fulfill({status:403,contentType:'application/json',body:JSON.stringify({error:'permissionError'})}));
 await page.goto('http://127.0.0.1:4205/?view=stops');await page.getByRole('alert').first().waitFor();
 assert.equal(await page.getByRole('button',{name:'Remove association',exact:true}).count(),0);
 assert.equal(await page.getByLabel('Scheduled maintenance (optional)').inputValue(),'');report.push('PASS reader denial discloses no associations; ordinary stop choice retained');
 assert.deepEqual(errors,[]);
 await writeFile(join(output,'results.json'),JSON.stringify({report,errors},null,2));console.log(report.join('\n'));
}finally{await browser.close();}
