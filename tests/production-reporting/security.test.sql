do $$declare x jsonb;f uuid;q jsonb:='{"reporting_version":3}';pkg uuid;begin
 select t.x into x from reporting_test.context t;f:=(x->>'factory')::uuid;
 perform reporting_test.ok(not has_table_privilege('authenticated','private.production_reporting_entries','SELECT'),'projection is private');
 perform reporting_test.ok(not has_function_privilege('authenticated','private.production_reporting_history(uuid,jsonb)','EXECUTE'),'internal reader revoked');
 perform reporting_test.ok(not has_function_privilege('authenticated','private.production_history_before_m3a(uuid,jsonb,text,text,integer)','EXECUTE'),'legacy delegate revoked');
 perform reporting_test.ok(not has_function_privilege('anon','public.production_history(uuid,jsonb,text,text,integer)','EXECUTE'),'anonymous execute denied');
 perform set_config('request.jwt.claim.sub','',false);
 perform reporting_test.fails(format('select public.production_history(%L,%L)',f,q),'42501');
 perform set_config('request.jwt.claim.sub',x->>'viewer',false);
 perform reporting_test.fails(format('select public.production_history(%L,%L)',f,q),'42501');
 perform set_config('request.jwt.claim.sub',x->>'owner',false);
 select id into pkg from public.permission_packages where factory_id=f and template_key='planning_engineer';
 perform public.set_member_permission_packages(f,(x->>'viewer')::uuid,array[pkg],array[]::uuid[]);
 perform set_config('request.jwt.claim.sub',x->>'viewer',false);
 perform reporting_test.ok((public.production_history(f,q)->>'total')::int>0,'package union reporting access');
 perform reporting_test.ok(private.has_permission(f,'lean','view'),'planning template includes its existing Lean view grant');
 perform reporting_test.fails(format('select public.production_history(%L,%L)',(select id from public.factories where id<>f limit 1),q),'42501');
 perform set_config('request.jwt.claim.sub',x->>'owner',false);
 perform public.set_member_permission_packages(f,(x->>'viewer')::uuid,array[]::uuid[],array[pkg]);
 perform set_config('request.jwt.claim.sub',x->>'viewer',false);
 perform reporting_test.fails(format('select public.production_history(%L,%L)',f,q),'42501');
 perform set_config('request.jwt.claim.sub',x->>'owner',false);
 perform public.set_member_direct_permissions(f,(x->>'viewer')::uuid,'[{"module":"factory","action":"view"},{"module":"maintenance","action":"view"},{"module":"orders","action":"view"}]',array['factory:view','maintenance:view']);
 perform set_config('request.jwt.claim.sub',x->>'viewer',false);
 perform reporting_test.ok(not private.has_permission(f,'lean','view'),'direct-grant fixture is Orders-only');
 perform reporting_test.ok(not exists(select 1 from jsonb_array_elements(public.production_history(f,q)->'rows')r where r->'lean_evidence'<>'null'::jsonb),'Orders-only cannot read Lean evidence');
 perform set_config('request.jwt.claim.sub',x->>'owner',false);
 perform public.set_member_direct_permissions(f,(x->>'viewer')::uuid,'[{"module":"factory","action":"view"},{"module":"maintenance","action":"view"}]',array['factory:view','maintenance:view','orders:view']);
end$$;
