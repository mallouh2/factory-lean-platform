-- Exercise real SQL role ACLs as well as real claim/grant evaluation.
grant usage on schema reporting_test to anon,authenticated;
grant insert on reporting_test.checks to anon,authenticated;
grant select on reporting_test.context to anon,authenticated;
select set_config('request.jwt.claim.sub','',false);
set role anon;
select reporting_test.fails(format('select public.production_history(%L,%L)',(select x->>'factory' from reporting_test.context),'{"reporting_version":3}'),'42501');
reset role;
select set_config('request.jwt.claim.sub',(select x->>'viewer' from reporting_test.context),false);
set role authenticated;
select reporting_test.fails(format('select public.production_history(%L,%L)',(select x->>'factory' from reporting_test.context),'{"reporting_version":3}'),'42501');
reset role;
